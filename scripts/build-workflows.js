// ---------- main ----------

const OUTPUTS = {
  'workflows/01-speed-to-lead-monitor-and-report.json': buildWorkflow1,
  'workflows/02-round-robin-lead-assignment.json': buildWorkflow2,
};

function compileCheck(wf, file) {
  for (const n of wf.nodes) {
    if (n.type !== 'n8n-nodes-base.code') continue;
    try {
      new Function('$input', '$', '$env', '$getWorkflowStaticData', n.parameters.jsCode);
    } catch (e) {
      throw new Error(`${file} > "${n.name}" does not compile: ${e.message}`);
    }
  }
}

const checkOnly = process.argv.includes('--check');
let failed = false;
for (const [file, build] of Object.entries(OUTPUTS)) {
  const wf = build();
  compileCheck(wf, file);
  const text = JSON.stringify(wf, null, 2) + '\n';
  const target = path.join(ROOT, file);
  if (checkOnly) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error(`OUT OF DATE: ${file} - run "npm run build"`);
      failed = true;
    } else {
      console.log(`ok  ${file} (${wf.nodes.length} nodes)`);
    }
  } else {
    fs.writeFileSync(target, text);
    console.log(`wrote ${file} (${wf.nodes.length} nodes)`);
  }
}
process.exit(failed ? 1 : 0);
