#!/usr/bin/env node
'use strict';

/**
 * Generates the n8n workflow JSON files in /workflows from the tested modules in /src and the
 * Code-node glue in /scripts/node-code.
 *
 *   node scripts/build-workflows.js           write workflows/*.json
 *   node scripts/build-workflows.js --check   verify workflows/*.json are up to date and every Code node compiles
 *
 * Edit src/ and scripts/node-code/, never the generated JSON.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');

// ---------- code inlining ----------

function stripModule(source) {
  return source
    .replace(/\/\/ @build:strip-start[\s\S]*?\/\/ @build:strip-end\n?/g, '')
    .replace(/^'use strict';\s*\n/m, '')
    .trim();
}

function assembleCode(modules, glueFile) {
  const parts = [
    '// Generated by scripts/build-workflows.js - edit src/ and scripts/node-code/, not this node.',
    ...modules.map((m) => `// ---- src/${m}.js ----\n${stripModule(read(`src/${m}.js`))}`),
    `// ---- node logic (scripts/node-code/${glueFile}) ----\n${read(`scripts/node-code/${glueFile}`).trim()}`,
  ];
  return parts.join('\n\n') + '\n';
}

// ---------- n8n node builders ----------

const uid = (name) => {
  const h = crypto.createHash('md5').update(name).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};

const HUBSPOT_CRED = { hubspotAppToken: { id: 'REPLACE_WITH_YOUR_CREDENTIAL_ID', name: 'HubSpot App Token' } };
const RETRY = { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 };

function node(name, type, typeVersion, position, parameters, extra) {
  return Object.assign({ parameters, id: uid(name), name, type, typeVersion, position }, extra || {});
}

const code = (name, position, modules, glueFile, notes) =>
  node(name, 'n8n-nodes-base.code', 2, position, { jsCode: assembleCode(modules, glueFile) }, notes ? { notes, notesInFlow: true } : {});

function hubspotHttp(name, position, { method = 'POST', url, jsonBody, query, notes }) {
  const parameters = {
    method,
    url,
    authentication: 'predefinedCredentialType',
    nodeCredentialType: 'hubspotAppToken',
    options: {},
  };
  if (jsonBody) Object.assign(parameters, { sendBody: true, specifyBody: 'json', jsonBody });
  if (query) Object.assign(parameters, { sendQuery: true, queryParameters: { parameters: query } });
  return node(name, 'n8n-nodes-base.httpRequest', 4.2, position, parameters, Object.assign({ credentials: HUBSPOT_CRED }, RETRY, notes ? { notes, notesInFlow: true } : {}));
}

const slackHttp = (name, position, bodyExpr) =>
  node(
    name,
    'n8n-nodes-base.httpRequest',
    4.2,
    position,
    { method: 'POST', url: '={{ $env.SLACK_WEBHOOK_URL }}', authentication: 'none', sendBody: true, specifyBody: 'json', jsonBody: bodyExpr, options: {} },
    Object.assign({ notes: 'Slack incoming webhook URL comes from the SLACK_WEBHOOK_URL environment variable.', notesInFlow: true }, RETRY)
  );

const setMode = (name, position, mode) =>
  node(name, 'n8n-nodes-base.set', 3.4, position, {
    assignments: { assignments: [{ id: uid(`${name}-mode`), name: 'mode', value: mode, type: 'string' }] },
    options: {},
  });

const ifBool = (name, position, conditions) =>
  node(name, 'n8n-nodes-base.if', 2.2, position, {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
      conditions: conditions.map(([left, operation], i) => ({
        id: uid(`${name}-${i}`),
        leftValue: left,
        rightValue: '',
        operator: { type: 'boolean', operation, singleValue: true },
      })),
      combinator: 'and',
    },
    options: {},
  });

const noOp = (name, position, notes) => node(name, 'n8n-nodes-base.noOp', 1, position, {}, notes ? { notes, notesInFlow: true } : {});

const sticky = (name, position, width, height, content, color) =>
  node(name, 'n8n-nodes-base.stickyNote', 1, position, { content, height, width, color: color || 4 });

function workflow(name, nodes, links) {
  const connections = {};
  for (const [from, to, outputIndex = 0] of links) {
    connections[from] = connections[from] || { main: [] };
    while (connections[from].main.length <= outputIndex) connections[from].main.push([]);
    connections[from].main[outputIndex].push({ node: to, type: 'main', index: 0 });
  }
  return {
    name,
    nodes,
    pinData: {},
    connections,
    active: false,
    settings: { executionOrder: 'v1' },
    versionId: uid(`${name}-version`),
    meta: { templateCredsSetupCompleted: false },
    tags: [],
  };
}

